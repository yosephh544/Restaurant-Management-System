let active: I18nService | null = null;

export function translate(text: string, params?: Record<string, string | number>): string {
  return active ? active.t(text, params) : text;
}

export function currentLang(): Lang {
  return active?.lang() ?? 'en';
}

export function locale(): string {
  return currentLang() === 'am' ? 'am-ET' : 'en-US';
}

let lastRouteTitle = 'Majete Corner';

export function applyRouteTitle(raw: string | null): void {
  lastRouteTitle = raw ?? 'Majete Corner';
  if (typeof document !== 'undefined') document.title = translate(lastRouteTitle);
}

export function refreshRouteTitle(): void {
  if (typeof document !== 'undefined') document.title = translate(lastRouteTitle);
}

@Injectable({ providedIn: 'root' })
export class I18nService {
  private uid: string | null = null;
  readonly lang = signal<Lang>('en');

  constructor() {
    active = this;
    this.lang.set(this.load());
    this.apply();
  }

  bindUser(uid: string | null): void {
    this.uid = uid;
    this.lang.set(this.load());
    this.apply();
  }

  setLang(lang: Lang): void {
    this.lang.set(lang);
    this.apply();
    try {
      localStorage.setItem(STORAGE_KEY, lang);
      if (this.uid) localStorage.setItem(`${STORAGE_KEY}.${this.uid}`, lang);
    } catch {
      // storage can be unavailable (private mode); language still applies for the session
    }
  }

  toggle(): void {
    this.setLang(this.lang() === 'am' ? 'en' : 'am');
  }

  t(text: string, params?: Record<string, string | number>): string {
    let value = this.lang() === 'am' ? AM[text] ?? text : text;
    if (params) {
      for (const [key, param] of Object.entries(params)) {
        value = value.replaceAll(`{${key}}`, String(param));
      }
    }
    return value;
  }

  private load(): Lang {
    try {
      const keys = this.uid ? [`${STORAGE_KEY}.${this.uid}`, STORAGE_KEY] : [STORAGE_KEY];
      for (const key of keys) {
        const value = localStorage.getItem(key);
        if (value === 'en' || value === 'am') return value;
      }
    } catch {
      // ignore storage errors and fall back to English
    }
    return 'en';
  }

  private apply(): void {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = this.lang();
      refreshRouteTitle();
    }
  }
}

@Pipe({ name: 't', standalone: true, pure: false })
export class TranslatePipe implements PipeTransform {
  private readonly i18n = inject(I18nService);

  transform(text: string, params?: Record<string, string | number>): string {
    return this.i18n.t(text, params);
  }
}
